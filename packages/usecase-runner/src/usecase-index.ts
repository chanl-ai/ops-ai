// One index of every use case for `list`: id, area, short title, the layers that have a script, and the doc. `index`
// writes it to docs/usecases/index.md; `list` builds the same rows in memory and adds each layer's last recorded run.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LAYERS, type Layer } from './layers.ts';
import type { UseCase } from './registry.ts';
import { verdict } from './report.ts';
import { resolveScript, USECASE_DIR } from './resolve.ts';
import { loadRun } from './stories.ts';

export interface IndexRow {
  id: string;
  area: string;
  title: string;
  /** Layers with a script on disk. */
  layers: Layer[];
  doc: string;
}

const SHORT = /^Short title:\s*(.+?)\s*$/m;
const ID = /Id: `(uc-\d{3})`/;

/** Doc path and short title by use case id; each doc is read once. */
function scanDocs(root: string, services: string[]): Map<string, { doc: string; short?: string }> {
  const found = new Map<string, { doc: string; short?: string }>();
  for (const service of services) {
    const dir = join(root, USECASE_DIR, service);
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir).filter((n) => n.endsWith('.md')).sort()) {
      const text = readFileSync(join(dir, name), 'utf8');
      const id = ID.exec(text)?.[1];
      if (id && !found.has(id)) found.set(id, { doc: `${USECASE_DIR}/${service}/${name}`, short: SHORT.exec(text)?.[1] });
    }
  }
  return found;
}

export function buildIndex(root: string, registry: UseCase[]): IndexRow[] {
  const docs = scanDocs(root, [...new Set(registry.map((u) => u.service))]);
  return registry.map((uc) => ({
    id: uc.id,
    area: uc.service,
    title: docs.get(uc.id)?.short ?? uc.title,
    layers: LAYERS.filter((l) => resolveScript(root, uc, l).kind === 'script'),
    doc: docs.get(uc.id)?.doc ?? '(no doc)',
  }));
}

export function formatIndex(rows: IndexRow[]): string {
  const lines = rows.map((r) => `| ${r.id} | ${r.area} | ${r.title.replace(/\|/g, '/')} | ${r.layers.join(', ') || 'none'} | \`${r.doc.replace(`${USECASE_DIR}/`, '')}\` |`);
  return `# Use case index

Status: current. Generated by \`make usecase-index\` from the registry in \`README.md\` and each doc; change those, not this file.
A doc's \`Short title:\` line gives the task name shown here; without one the registry title is used. Layers are the
ones with a script. \`make usecase-list\` adds each layer's last recorded run.

| Id | Area | Short title | Layers | Doc |
|---|---|---|---|---|
${lines.join('\n')}
`;
}

export function writeIndex(root: string, rows: IndexRow[]): string {
  const path = `${USECASE_DIR}/index.md`;
  writeFileSync(join(root, path), formatIndex(rows));
  return path;
}

/** "api ok, ui FAILED" from the saved runs, or "not run". */
export function lastRun(root: string, row: IndexRow): string {
  const parts = row.layers.flatMap((l) => {
    const run = loadRun(root, row.id, l);
    return run ? [`${l} ${verdict(run.exit, run.checks).pass ? 'ok' : 'FAILED'}`] : [];
  });
  return parts.join(', ') || 'not run';
}

/** `area` matches a service name or the name without "-service". */
export function inArea(row: IndexRow, area?: string): boolean {
  return !area || row.area === area || row.area === `${area}-service`;
}

export function formatList(root: string, rows: IndexRow[]): string {
  const w = (f: (r: IndexRow) => string) => Math.max(...rows.map((r) => f(r).length));
  const aw = w((r) => r.area);
  const tw = Math.min(60, w((r) => r.title));
  const lw = w((r) => r.layers.join(',') || 'none');
  const head = `${'id'.padEnd(6)}  ${'area'.padEnd(aw)}  ${'title'.padEnd(tw)}  ${'layers'.padEnd(lw)}  last run`;
  const body = rows.map(
    (r) => `${r.id.padEnd(6)}  ${r.area.padEnd(aw)}  ${(r.title.length > tw ? `${r.title.slice(0, tw - 1)}…` : r.title).padEnd(tw)}  ${(r.layers.join(',') || 'none').padEnd(lw)}  ${lastRun(root, r)}`,
  );
  return rows.length ? [head, ...body, `${rows.length} use cases`].join('\n') : 'no use case in that area';
}
