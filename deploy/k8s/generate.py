@dataclass(frozen=True)
class Workload:
    name: str
    image: str  # the deploy/fly/Dockerfile target, as ops-ai/<image>
    port: int | None = None
    # Every probe reads this unless `live_tcp`: then startup and liveness only check the port and readiness alone reads
    # it (agents answers 503 until a model is connected, which takes it out of the Service and never restarts it).
    health: str | None = None
    live_tcp: bool = False
    command: list[str] = field(default_factory=lambda: [])
    env: dict[str, str] = field(default_factory=lambda: {})
    secret: str | None = None  # the Secret holding this workload's keys and login (generated by the overlay)
    settings: bool = True  # reads the shared settings and the overlay's origin settings
    data: bool = False  # a PersistentVolumeClaim at /data (file and knowledge-base bytes)
    exec_probe: list[str] = field(default_factory=lambda: [])
    memory: str = "256Mi"
    # Paths the process writes besides /tmp, each an emptyDir under a read-only root filesystem.
    scratch: tuple[str, ...] = ()
    # The console copies its build to .next at every start (deploy/images/console-start.mjs) and Next writes its cache
    # there, inside a folder of the image; a mount cannot stand in, since the copy first deletes the folder.
    writable_root: bool = False


