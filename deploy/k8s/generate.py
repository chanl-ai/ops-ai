"""Writes the Kustomize base (deploy/k8s/base/): one folder per workload (a Deployment, and a Service when it serves a
port), the settings every Python service shares, the migrate Job and the outside-Postgres Service. One table here is
the source for the workloads, and the shared settings are read from the compose file's x-settings, so the two never
disagree. The YAML it writes is committed so a reviewer reads plain manifests. Runbook: docs/deploy/kubernetes.md.

    uv run python deploy/k8s/generate.py            writes deploy/k8s/base/
    uv run python deploy/k8s/generate.py --check    exit 1 when the committed base is not what this file writes
"""

