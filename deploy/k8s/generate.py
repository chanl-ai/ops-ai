# platform's internal port (API-key introspection, ops_identity.fastapi.Auth.from_settings): only these may reach it.
INTERNAL_PORT = 8711
INTERNAL_CLIENTS = ("agents", "tools", "models", "kb", "files", "documents")
# Compose settings the overlay supplies (its ops-origin ConfigMap) or each service's Secret holds.
ORIGIN_SETTINGS = {"OPS_CORS_ORIGINS", "OPS_CONSOLE_URL", "OPS_PLATFORM_PUBLIC_URL", "OPS_FILES_PUBLIC_URL"}
SECRET_SETTINGS = {"OPS_SERVICE_PUBLIC_KEYS"}
_DEFAULTED = re.compile(r"^\$\{\w+:-(.*)\}$")


def settings() -> dict[str, str]:
    """What every Python service reads besides its Secret, from deploy/compose/app.yaml's x-settings: the service
    names are the same on both, so each address carries over. A `${X:-default}` value becomes its default (an empty
    one is left unset); the origin and secret settings are the overlay's and the Secret's. Any other setting compose
    requires from its env file is refused by name, so it gets a home here before it reaches a cluster."""
    compose = yaml.safe_load(COMPOSE.read_text())
    out: dict[str, str] = {}
    for key, raw in compose["x-settings"].items():
        value = str(raw)
        if key in ORIGIN_SETTINGS | SECRET_SETTINGS:
            continue
        if "${" not in value:
            out[key] = value
        elif m := _DEFAULTED.match(value):
            if m.group(1):
                out[key] = m.group(1)
        else:
            raise SystemExit(f"generate: compose's {key} needs a value from its env file; give it one here")
    return out


def dump(docs: list[Any]) -> str:
    return "".join("---\n" + yaml.safe_dump(d, sort_keys=False, width=120) for d in docs)


def labels(name: str) -> dict[str, str]:
    return {"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": "ops-ai"}


def http(path: str, port: int) -> dict[str, Any]:
    return {"httpGet": {"path": path, "port": port}}


def container(w: Workload) -> dict[str, Any]:
    c: dict[str, Any] = {
        "name": w.name,
        "image": f"ops-ai/{w.image}",
        "imagePullPolicy": "IfNotPresent",
        "env": [{"name": k, "value": v} for k, v in w.env.items()],
        "resources": {"requests": {"cpu": "50m", "memory": w.memory}, "limits": {"memory": w.memory}},
        "securityContext": {
            "allowPrivilegeEscalation": False,
            "capabilities": {"drop": ["ALL"]},
            "readOnlyRootFilesystem": not w.writable_root,
        },
    }
    if w.command:
        c["command"] = w.command
    sources: list[dict[str, Any]] = []
    if w.settings:
        sources += [{"configMapRef": {"name": "ops-settings"}}, {"configMapRef": {"name": "ops-origin"}}]
    if w.name == "console":
        sources += [{"configMapRef": {"name": "ops-console"}}]
    if w.secret:
        sources += [{"secretRef": {"name": f"ops-{w.secret}"}}]
    if sources:
        c["envFrom"] = sources
    if w.port:
        c["ports"] = [{"containerPort": w.port, "name": "http"}]
    if w.port and w.health:
        start = {"tcpSocket": {"port": w.port}} if w.live_tcp else http(w.health, w.port)
        c["startupProbe"] = {**start, "periodSeconds": 3, "failureThreshold": 60}
        c["readinessProbe"] = {**http(w.health, w.port), "periodSeconds": 10, "failureThreshold": 3}
        live = {"tcpSocket": {"port": w.port}} if w.live_tcp else http(w.health, w.port)
        c["livenessProbe"] = {**live, "periodSeconds": 20, "failureThreshold": 3}
    if w.exec_probe:
        c["livenessProbe"] = {"exec": {"command": w.exec_probe}, "periodSeconds": 30, "timeoutSeconds": 10}
    mounts = [{"name": "tmp", "mountPath": "/tmp"}]
    mounts += [{"name": _scratch_name(path), "mountPath": path} for path in w.scratch]
    if w.data:
        mounts.append({"name": "data", "mountPath": "/data"})
    c["volumeMounts"] = mounts
    return c


def _scratch_name(path: str) -> str:
    return "scratch" + path.replace("/", "-")


POD_SECURITY = {
    "runAsNonRoot": True,
    "runAsUser": UID,
    "runAsGroup": UID,
    "fsGroup": UID,
    "seccompProfile": {"type": "RuntimeDefault"},
}


def workload(w: Workload) -> str:
    pod: dict[str, Any] = {"securityContext": POD_SECURITY, "containers": [container(w)]}
    pod["volumes"] = [{"name": "tmp", "emptyDir": {}}, *({"name": _scratch_name(p), "emptyDir": {}} for p in w.scratch)]
    docs: list[dict[str, Any]] = []
    if w.data:
        pod["volumes"].append({"name": "data", "persistentVolumeClaim": {"claimName": f"{w.name}-data"}})
        docs.append(
            {
                "apiVersion": "v1",
                "kind": "PersistentVolumeClaim",
                "metadata": {"name": f"{w.name}-data", "labels": labels(w.name)},
                "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": "1Gi"}}},
            }
        )
    docs.append(
        {
            "apiVersion": "apps/v1",
            "kind": "Deployment",
            "metadata": {"name": w.name, "labels": labels(w.name)},
            "spec": {
                "replicas": 1,
                # A volume a pod holds ReadWriteOnce is released before the next pod takes it.
                "strategy": {"type": "Recreate"} if w.data else {"type": "RollingUpdate"},
                "selector": {"matchLabels": {"app.kubernetes.io/name": w.name}},
                "template": {"metadata": {"labels": labels(w.name)}, "spec": pod},
            },
        }
    )
    if w.port:
        ports = [{"name": "http", "port": w.port, "targetPort": w.port}]
        if w.name == "platform":
            # API-key introspection, with a service token; the NetworkPolicy below admits only its clients.
            ports.append({"name": "internal", "port": INTERNAL_PORT, "targetPort": INTERNAL_PORT})
        docs.append(
            {
                "apiVersion": "v1",
                "kind": "Service",
                "metadata": {"name": w.name, "labels": labels(w.name)},
                "spec": {"selector": {"app.kubernetes.io/name": w.name}, "ports": ports},
            }
        )
        if w.name == "platform":
            docs.append(internal_policy(w.port))
    return dump(docs)


def internal_policy(public_port: int) -> dict[str, Any]:
    """Ingress to platform: its public port from any pod, the internal port only from the services that introspect API
    keys. Selecting the pods denies every other ingress, but only where the cluster's network plugin enforces
    NetworkPolicy."""
    unknown = set(INTERNAL_CLIENTS) - {w.name for w in WORKLOADS}
    if unknown:
        raise SystemExit(f"generate: INTERNAL_CLIENTS names no workload: {sorted(unknown)}")
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "NetworkPolicy",
        "metadata": {"name": "platform-internal", "labels": labels("platform")},
        "spec": {
            "podSelector": {"matchLabels": {"app.kubernetes.io/name": "platform"}},
            "policyTypes": ["Ingress"],
            "ingress": [
                {"ports": [{"protocol": "TCP", "port": public_port}]},
                {
                    "from": [
                        {
                            "podSelector": {
                                "matchExpressions": [
                                    {
                                        "key": "app.kubernetes.io/name",
                                        "operator": "In",
                                        "values": list(INTERNAL_CLIENTS),
                                    }
                                ]
                            }
                        }
                    ],
                    "ports": [{"protocol": "TCP", "port": INTERNAL_PORT}],
                },
            ],
        },
    }


def shared() -> dict[str, str]:
    config = {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "ops-settings"}, "data": settings()}
    # Every chain, then the first admin (deploy/images/migrate.sh), with the migrator's login. A Job's template cannot
    # change, so an upgrade deletes the finished Job and applies again (docs/deploy/kubernetes.md).
    job = {
        "apiVersion": "batch/v1",
        "kind": "Job",
        "metadata": {"name": "migrate", "labels": labels("migrate")},
        "spec": {
            "backoffLimit": 3,
            "template": {
                "metadata": {"labels": labels("migrate")},
                "spec": {
                    "restartPolicy": "Never",
                    "securityContext": {k: v for k, v in POD_SECURITY.items() if k != "fsGroup"},
                    "volumes": [{"name": "tmp", "emptyDir": {}}],
                    "containers": [
                        {
                            "name": "migrate",
                            "image": "ops-ai/platform",
                            "imagePullPolicy": "IfNotPresent",
                            "args": ["migrate"],
                            "envFrom": [
                                {"configMapRef": {"name": "ops-settings"}},
                                {"configMapRef": {"name": "ops-origin"}},
                                {"secretRef": {"name": "ops-migrate"}},
                            ],
                            "securityContext": {
                                "allowPrivilegeEscalation": False,
                                "capabilities": {"drop": ["ALL"]},
                                "readOnlyRootFilesystem": True,
                            },
                            "volumeMounts": [{"name": "tmp", "mountPath": "/tmp"}],
                        }
                    ],
                },
            },
        },
    }
    # The outside database under a stable name: no selector, so the overlay supplies where it is (an EndpointSlice
    # with its address, or a patch to type ExternalName with its host name).
    postgres = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": "postgres", "labels": labels("postgres")},
        "spec": {"ports": [{"name": "postgres", "port": 5432, "targetPort": 5432}]},
    }
    # Every object lands in this namespace; an overlay's `namespace:` renames it everywhere.
    namespace = {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": "ops-ai"}}
    return {
        "namespace.yaml": dump([namespace]),
        "settings.yaml": dump([config]),
        "migrate-job.yaml": dump([job]),
        "postgres.yaml": dump([postgres]),
    }


HEAD = "# Generated by deploy/k8s/generate.py; edit there. Overlays: deploy/k8s/overlays/.\n"


def render() -> dict[str, str]:
    """Every file of the base, by its path under it."""
    files = {f"shared/{name}": text for name, text in shared().items()}
    files |= {f"{w.name}/workload.yaml": workload(w) for w in WORKLOADS}
    files["kustomization.yaml"] = (
        HEAD
        + "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n"
        + "".join(f"  - {r}\n" for r in files)
    )
    return files


def stale(files: dict[str, str]) -> list[str]:
    """The base's files that differ from `files`, are missing, or are no longer written."""
    on_disk = {str(p.relative_to(BASE)) for p in BASE.rglob("*.yaml")}
    out = [n for n, text in files.items() if not (BASE / n).is_file() or (BASE / n).read_text() != text]
    return sorted(out + sorted(on_disk - set(files)))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when deploy/k8s/base is not what this file writes")
    files = render()
    if ap.parse_args().check:
        if bad := stale(files):
            print("generate: deploy/k8s/base is stale; run uv run python deploy/k8s/generate.py", file=sys.stderr)
            print("".join(f"  {n}\n" for n in bad), end="", file=sys.stderr)
            sys.exit(1)
        print(f"generate: deploy/k8s/base matches ({len(files)} files)")
        return
    for name, text in files.items():
        (BASE / name).parent.mkdir(parents=True, exist_ok=True)
        (BASE / name).write_text(text)
    print(f"wrote {len(files)} files in {BASE.relative_to(HERE.parents[1])}")


if __name__ == "__main__":
    main()
