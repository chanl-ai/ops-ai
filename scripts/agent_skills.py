"""Writes the developer skills for Claude Code and GitHub Copilot from their one copy in docs/guide/skills/ (c-554).

    python3 scripts/agent_skills.py           write .claude/skills/ops-*/SKILL.md, .github/prompts/ops-*.prompt.md and
                                              .github/copilot-instructions.md
    python3 scripts/agent_skills.py --check   exit 1 when a written file differs from its page, a page is malformed,
                                              or a generated file has no page (make verify runs this)

A page has a title, a Status line, `skill:`, `description:` and `targets:` lines, its sections, and one fenced
`bash proof` block that `make skills-proof` runs. The standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / "docs" / "guide" / "skills"
CLAUDE_SKILLS = ROOT / ".claude" / "skills"
PROMPTS = ROOT / ".github" / "prompts"
INSTRUCTIONS = ROOT / ".github" / "copilot-instructions.md"
PREFIX = "ops-"
# Copilot reads the instructions file on every request and asks for about two pages at most.
MAX_INSTRUCTION_WORDS = 1000
ALLOWED_TOOLS = "Bash(make *) Bash(uv run *) Bash(python3 *) Read Grep Glob"
PROOF = re.compile(r"^```bash proof\n(.*?)^```", re.M | re.S)


@dataclass(frozen=True)
class Skill:
    name: str
    title: str
    description: str
    targets: str
    body: str
    proof: str
    page: Path

    def source_note(self) -> str:
        page = self.page.relative_to(ROOT)
        return f"Generated from `{page}` by `scripts/agent_skills.py`; change the page, not this file."


def parse(page: Path) -> Skill:
    text = page.read_text()
    fields = dict(re.findall(r"^(skill|description|targets): (.+)$", text, re.M))
    title = text.splitlines()[0].removeprefix("# ").strip()
    missing = [f for f in ("skill", "description", "targets") if f not in fields]
    if missing:
        raise ValueError(f"{page.relative_to(ROOT)}: no {', '.join(missing)} line")
    proof = PROOF.search(text)
    if proof is None:
        raise ValueError(f"{page.relative_to(ROOT)}: no ```bash proof block")
    start = text.index("\n## ")
    return Skill(fields["skill"], title, fields["description"], fields["targets"], text[start:].strip(), proof[1], page)


def skills() -> list[Skill]:
    return [parse(p) for p in sorted(PAGES.glob("*.md"))]


def process_skills() -> set[str]:
    """The codeloop process skills already beside the generated ones, which a developer skill may not shadow."""
    if not CLAUDE_SKILLS.exists():
        return set()
    return {p.name for p in CLAUDE_SKILLS.iterdir() if p.is_dir() and not p.name.startswith(PREFIX)}


def claude_skill(s: Skill) -> str:
    return (
        f"---\nname: {s.name}\ndescription: {s.description}\nallowed-tools: {ALLOWED_TOOLS}\n---\n\n"
        f"# {s.title}\n\n<!-- {s.source_note()} -->\n\nMake targets: {s.targets}.\n\n{s.body}\n"
    )


def prompt(s: Skill) -> str:
    return (
        f"---\nname: {s.name}\ndescription: {s.description}\nagent: agent\n---\n\n"
        f"# {s.title}\n\n<!-- {s.source_note()} -->\n\nMake targets: {s.targets}.\n\n{s.body}\n"
    )


def _section(text: str, heading: str) -> str:
    """One `## heading` section of a markdown file, without its heading line."""
    found = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return found[1].strip() if found else ""


def instructions(all_skills: list[Skill]) -> str:
    agents = (ROOT / "AGENTS.md").read_text()
    table = agents[agents.index("| Rule |") :].strip()
    rules = _section((ROOT / "CLAUDE.md").read_text(), "Four rules every change follows")
    index = "\n".join(f"| `/{s.name}` | {s.description} |" for s in all_skills)
    return (
        "# Ops AI for GitHub Copilot\n\n"
        "<!-- Generated by `scripts/agent_skills.py` from AGENTS.md, CLAUDE.md and docs/guide/skills/; "
        "change those. -->\n\n"
        "Ops AI is an operational AI platform: Python services in `services/`, libraries in `packages/`, "
        "a Next.js console in `apps/console/`, all run through the root `Makefile` (`make help`). "
        "Design docs start at `docs/README.md`.\n\n"
        f"## Rules for coding agents\n\n{table}\n\n## Four rules every change follows\n\n{rules}\n\n"
        "## Prompts for common tasks\n\nEach runs the make targets it names; the same steps are Claude Code skills of "
        f"the same name.\n\n| Prompt | Use it to |\n|---|---|\n{index}\n"
    )


def expected() -> dict[Path, str]:
    all_skills = skills()
    out = {CLAUDE_SKILLS / s.name / "SKILL.md": claude_skill(s) for s in all_skills}
    out |= {PROMPTS / f"{s.name}.prompt.md": prompt(s) for s in all_skills}
    out[INSTRUCTIONS] = instructions(all_skills)
    return out


def problems(files: dict[Path, str]) -> list[str]:
    out: list[str] = []
    taken = process_skills()
    for s in skills():
        if not s.name.startswith(PREFIX):
            out.append(f"{s.page.relative_to(ROOT)}: skill {s.name} does not start with {PREFIX}")
        if s.name in taken:
            out.append(f"{s.page.relative_to(ROOT)}: {s.name} is a process skill's name")
        if s.page.stem != s.name:
            out.append(f"{s.page.relative_to(ROOT)}: the page is named {s.page.stem}, the skill {s.name}")
    words = len(files[INSTRUCTIONS].split())
    if words > MAX_INSTRUCTION_WORDS:
        out.append(f"{INSTRUCTIONS.relative_to(ROOT)}: {words} words, over {MAX_INSTRUCTION_WORDS}")
    return out


def stale(files: dict[Path, str]) -> list[str]:
    """Written files that differ from what the pages give, are missing, or have no page any more."""
    on_disk = set(CLAUDE_SKILLS.glob(f"{PREFIX}*/SKILL.md")) | set(PROMPTS.glob(f"{PREFIX}*.prompt.md"))
    out = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
    return sorted(out + [str(p.relative_to(ROOT)) for p in on_disk - set(files)])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when a written file differs from its page")
    a = ap.parse_args()
    try:
        files = expected()
    except ValueError as e:
        print(f"agent-skills: {e}", file=sys.stderr)
        return 1
    bad = problems(files)
    if a.check:
        bad += [f"{name} is not what its page gives; run python3 scripts/agent_skills.py" for name in stale(files)]
        for line in bad:
            print(f"agent-skills: {line}", file=sys.stderr)
        if not bad:
            print(f"agent-skills: {len(files)} files match docs/guide/skills/")
        return 1 if bad else 0
    if bad:
        print("\n".join(f"agent-skills: {line}" for line in bad), file=sys.stderr)
        return 1
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"agent-skills: wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
