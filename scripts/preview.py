"""Preview stacks: one worktree and one running stack per branch under review, at most three.

make wt BRANCH=x | wt-list | wt-stop BRANCH=x  (make/preview.mk). A preview is the ordinary stack started with
OPS_PORT_OFFSET from its own worktree, so its ports, compose project, pids, logs and data are already separate from
:3016 and from each other; this script only picks the offset, keeps the list and writes the page.

Registry: one JSON file per preview in <run root>/previews. A preview counts as running while its console pid is alive,
or, during start, while the `make wt` process that is starting it is."""

from __future__ import annotations

import argparse
import contextlib
import html
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIMIT = 3
# Clear of the default stack and of the offsets tests and lanes use. Not 50000: the mail ports move by offset/10 and
# GreenMail's SMTP (3025 + 5000) would land on the default stack's Mailpit (8025).
FIRST_OFFSET = 51000
STEP = 1000
# Offsets tried, in order. Those whose highest port is over MAX_PORT are listed and refused by name, so a machine with
# every usable offset taken says why instead of "no free slot".
CANDIDATES = 10
MAX_PORT = 65535
CONSOLE_BASE = 3016
# Ports the stack does not bind when OPS_INFRA=external (postgres, opa and the mail servers run as side containers).
INFRA_PORTS = ("OPS_PG_PORT", "OPS_OPA_PORT", "OPS_GREENMAIL_", "OPS_MAILPIT_")


def alive(pid: int) -> bool:
    if pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def slug(branch: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]", "_", branch)


class Previews:
    def __init__(self, run_root: Path, page: Path | None, data_root: Path | None = None):
        self.run_root, self.page = run_root, page
        self.data_root = data_root or run_root.parent / ".data"
        self.reg = run_root / "previews"

    def entries(self) -> list[dict]:
        out = []
        for f in sorted(self.reg.glob("*.json")) if self.reg.is_dir() else []:
            try:
                e = json.loads(f.read_text())
            except ValueError:
                continue
            e["file"] = str(f)
            e["running"] = self.running(e)
            out.append(e)
        return out

    def running(self, e: dict) -> bool:
        pidfile = self.run_root / f"offset-{e['offset']}" / "console.pid"
        try:
            if alive(int(pidfile.read_text().strip())):
                return True
        except (OSError, ValueError):
            pass
        return alive(int(e.get("starter", 0)))

    def url(self, e: dict) -> str:
        return f"http://localhost:{CONSOLE_BASE + int(e['offset'])}"

    def age(self, e: dict) -> str:
        s = max(0, int(time.time() - float(e["started"])))
        return f"{s // 86400}d" if s >= 86400 else f"{s // 3600}h" if s >= 3600 else f"{s // 60}m"

    def write_page(self) -> None:
        if self.page is None:
            return

        def cell(e: dict) -> str:
            if not e["running"]:
                return "stopped"
            u = self.url(e)
            return f'<a href="{u}">{u}</a>'

        rows = (
            "".join(
                f"<tr><td>{html.escape(e['branch'])}</td><td>{cell(e)}</td><td>{self.age(e)}</td></tr>"
                for e in self.entries()
            )
            or '<tr><td colspan="3">No previews running.</td></tr>'
        )
        self.page.parent.mkdir(parents=True, exist_ok=True)
        self.page.write_text(
            '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" '
            'content="width=device-width,initial-scale=1"><title>Ops AI previews</title>'
            "<style>:root{color-scheme:light dark}body{font:15px system-ui;margin:2rem 16px;max-width:60rem}"
            "table{border-collapse:collapse;width:100%}td,th{padding:.4rem .6rem;text-align:left;"
            "border-bottom:1px solid #8884}</style></head><body><h1>Ops AI previews</h1>"
            "<p>One stack per branch in review, at most three. Regenerated by <code>make wt-list</code>; "
            ":3016 runs the latest main.</p><table><tr><th>Branch</th><th>Console</th><th>Age</th></tr>"
            f"{rows}</table><p>Generated {time.strftime('%Y-%m-%d %H:%M')}.</p></body></html>\n"
        )

    def listing(self) -> int:
        es = self.entries()
        for e in es:
            print(f"{e['branch']}\t{self.url(e) if e['running'] else 'stopped'}\t{self.age(e)}")
        if not es:
            print("no previews")
        self.write_page()
        return 0

    def pick(self, branch: str) -> tuple[int, str | None]:
        """The offset for a new preview, or (0, reason) when the branch has one or three already run."""
        live = [e for e in self.entries() if e["running"]]
        for e in live:
            if e["branch"] == branch:
                return 0, f"{branch} already has a preview: {self.url(e)}"
        if len(live) >= LIMIT:
            names = ", ".join(f"{e['branch']} ({self.url(e)})" for e in live)
            return 0, f"refused: {LIMIT} previews already run: {names}. Stop one with make wt-stop BRANCH=<branch>."
        return self.first_usable(branch, live)

    def data_owner(self, offset: int) -> str | None:
        """The branch the offset's data folder belongs to: its marker, else the registry entry at that offset.
        None when the folder holds data nobody here claims."""
        marker = self.data_root / f"offset-{offset}" / "branch"
        try:
            return marker.read_text().strip() or None
        except OSError:
            pass
        for e in self.entries():
            if int(e["offset"]) == offset:
                self.mark_data(offset, e["branch"])
                return e["branch"]
        return None

    def data_size(self, offset: int) -> str:
        total = sum(f.stat().st_size for f in (self.data_root / f"offset-{offset}").rglob("*") if f.is_file())
        return f"{total / 1e6:.0f} MB" if total >= 1e6 else f"{total // 1000} KB"

    def mark_data(self, offset: int, branch: str) -> None:
        d = self.data_root / f"offset-{offset}"
        d.mkdir(parents=True, exist_ok=True)
        (d / "branch").write_text(branch)

    def own_pids(self, offset: int) -> set[int]:
        pids: set[int] = set()
        for f in (self.run_root / f"offset-{offset}").glob("*.pid"):
            with contextlib.suppress(OSError, ValueError):
                pids.add(int(f.read_text().strip()))
        return pids

    def first_usable(self, branch: str, live: list[dict]) -> tuple[int, str | None]:
        listeners = listening()
        taken = {int(e["offset"]): e for e in live}
        why: list[str] = []
        for n in range(CANDIDATES):
            off = FIRST_OFFSET + n * STEP
            if off in taken:
                why.append(f"{off} (preview {taken[off]['branch']})")
                continue
            held = blockers(ports_for(off, clean_env()), listeners, set())
            if (self.data_root / f"offset-{off}").is_dir() and self.data_owner(off) != branch:
                owner = self.data_owner(off)
                held.append(
                    f"data in .data/offset-{off} ({self.data_size(off)}) belongs to "
                    + (owner or "no known branch; the owner can remove the folder to reuse the offset")
                )
            if held:
                why.append(f"{off} ({brief(held)})")
                continue
            return off, None
        return 0, "refused: no usable offset: " + ", ".join(why)

    def register(self, branch: str, offset: int, directory: Path) -> Path:
        self.reg.mkdir(parents=True, exist_ok=True)
        f = self.reg / f"{slug(branch)}.json"
        f.write_text(
            json.dumps(
                {
                    "branch": branch,
                    "offset": offset,
                    "dir": str(directory),
                    "started": time.time(),
                    "starter": os.getppid(),
                }
            )
        )
        return f


def clean_env() -> dict[str, str]:
    """The environment a preview's make runs in. The caller's make exported its own :3016 stack's ports and URLs
    (OPS_*), and a variable already in the environment beats the offset's value, so the preview would bind the
    default stack's ports; only OPS_INFRA is a choice the caller makes for every stack."""
    drop = ("OPS_", "STACK_HOME", "MAKEFLAGS", "MFLAGS")
    return {k: v for k, v in os.environ.items() if k == "OPS_INFRA" or not k.startswith(drop)}


def run(*cmd: str, cwd: Path | None = None, check: bool = True) -> subprocess.CompletedProcess:
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(cmd, cwd=cwd, check=check)


def ports_for(offset: int, env: dict[str, str]) -> dict[int, str]:
    """Every port the stack binds at this offset, as {port: variable}. They come from make/env.mk through
    `make port-list`, the one place the ports are defined; this script keeps no list of its own."""
    cmd = ["make", "-s", "-C", str(ROOT), "port-list", f"OPS_PORT_OFFSET={offset}"]
    r = subprocess.run(cmd, capture_output=True, text=True, env=env, check=False)
    out: dict[int, str] = {}
    for line in r.stdout.splitlines():
        name, _, val = line.partition("=")
        if not val.strip().isdigit():
            continue
        if env.get("OPS_INFRA") == "external" and name.startswith(INFRA_PORTS):
            continue
        out[int(val)] = name
    if not out:
        raise SystemExit(f"preview: make port-list printed no ports: {r.stderr.strip()}")
    return out


def listening() -> dict[int, list[tuple[int, str]]]:
    """{port: [(pid, command)]} for every TCP listener, from one lsof call."""
    r = subprocess.run(["lsof", "-nP", "-iTCP", "-sTCP:LISTEN", "-Fpcn"], capture_output=True, text=True, check=False)
    out: dict[int, list[tuple[int, str]]] = {}
    pid, cmd = 0, ""
    for line in r.stdout.splitlines():
        if line[:1] == "p" and line[1:].isdigit():
            pid, cmd = int(line[1:]), ""
        elif line[:1] == "c":
            cmd = line[1:]
        elif line[:1] == "n" and ":" in line:
            tail = line.rsplit(":", 1)[1]
            if tail.isdigit():
                out.setdefault(int(tail), []).append((pid, cmd))
    return out


def docker_ports(project: str) -> set[int]:
    """Host ports the compose project's containers publish; docker's own process holds them, not the stack's pids."""
    r = subprocess.run(
        ["docker", "ps", "--filter", f"label=com.docker.compose.project={project}", "--format", "{{.Ports}}"],
        capture_output=True,
        text=True,
        check=False,
    )
    return {int(m) for m in re.findall(r":(\d+)->", r.stdout)}


def brief(held: list[str], limit: int = 2) -> str:
    """The first few blockers of one offset, so a refusal stays one readable line."""
    more = f" (+{len(held) - limit} more)" if len(held) > limit else ""
    return "; ".join(held[:limit]) + more


def blockers(
    ports: dict[int, str], listeners: dict[int, list[tuple[int, str]]], own: set[int], own_ports: set[int] | None = None
) -> list[str]:
    """What stops a stack using these ports: a port over MAX_PORT, or a listener that is not in `own`."""
    out = []
    if max(ports) > MAX_PORT:
        out.append(f"ports run up to {max(ports)}, above {MAX_PORT}")
    for port in sorted(ports):
        if port > MAX_PORT:
            continue
        for pid, cmd in listeners.get(port, []):
            if pid in own or port in (own_ports or set()):
                continue
            out.append(f"port {port} ({ports[port]}) held by pid {pid} {cmd}")
    return out


def start(p: Previews, a: argparse.Namespace) -> int:
    off, why = p.pick(a.branch)
    if why:
        print(why, file=sys.stderr)
        return 1
    home, wt = Path(a.home), Path(a.worktrees) / a.branch
    if a.dry_run:
        print(f"would start {a.branch} at offset {off} in {wt}")
        return 0
    entry = p.register(a.branch, off, wt)
    p.mark_data(off, a.branch)
    try:
        git = ["git", "-C", str(home)]
        run(*git, "fetch", "-q", "origin", f"+refs/heads/{a.branch}:refs/remotes/origin/{a.branch}", check=False)
        have_remote = (
            subprocess.run(
                [*git, "rev-parse", "-q", "--verify", f"origin/{a.branch}"], capture_output=True, check=False
            ).returncode
            == 0
        )
        if not (wt / ".git").exists():
            wt.parent.mkdir(parents=True, exist_ok=True)
            # Detached, as make review does, so a branch checked out in another worktree can still be previewed.
            run(*git, "worktree", "add", "-q", "--detach", str(wt), f"origin/{a.branch}" if have_remote else a.branch)
        for f in (".env", ".devcontainer/.env.local"):
            if (home / f).is_file() and not (wt / f).exists():
                (wt / f).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(home / f, wt / f)
        # pnpm and uv keep one content-addressed store per user; a worktree links from it instead of downloading.
        env = {**clean_env(), "npm_config_prefer_offline": "true"}
        subprocess.run(["make", "-s", "-C", str(wt), "install"], check=True, env=env)
        subprocess.run(
            [
                "make",
                "-C",
                str(wt),
                "up",
                f"OPS_PORT_OFFSET={off}",
                "AUTH=platform",
                f"DEMO_MODEL={os.environ.get('DEMO_MODEL', 'fake')}",
            ],
            check=True,
            env=clean_env(),
        )
    except (subprocess.CalledProcessError, OSError) as e:
        # Containers a half-finished up created would hold the offset's ports; their data volume stays.
        subprocess.run(
            ["make", "-C", str(wt), "down", f"OPS_PORT_OFFSET={off}"], env=clean_env(), capture_output=True, check=False
        )
        entry.unlink(missing_ok=True)
        print(f"wt failed: {e}; nothing left registered", file=sys.stderr)
        p.write_page()
        return 1
    # The registry now answers from the console pid; the starter pid was only for the minutes before it existed.
    d = json.loads(entry.read_text())
    d["starter"] = 0
    entry.write_text(json.dumps(d))
    print(f"preview: {a.branch} on {p.url(d)}, run from {wt}")
    p.write_page()
    return 0


def check_offset(p: Previews, a: argparse.Namespace) -> int:
    """`make up OPS_PORT_OFFSET=N`: refuse when a port of N is held by something that is not this checkout's stack at N,
    or N belongs to another preview's worktree. Same blockers() as the offset picker."""
    off, root = a.offset, Path(a.root).resolve()
    held = []
    for e in p.entries():
        if int(e["offset"]) == off and e["running"] and Path(e["dir"]).resolve() != root:
            held.append(f"offset {off} runs the preview of {e['branch']} ({e['dir']})")
    branch = (
        a.branch
        or subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--abbrev-ref", "HEAD"], capture_output=True, text=True, check=False
        ).stdout.strip()
    )
    if branch and branch != "HEAD" and (p.data_root / f"offset-{off}").is_dir():
        marker = p.data_root / f"offset-{off}" / "branch"
        if not marker.exists():
            p.mark_data(off, branch)  # a hand-started stack's folder, claimed by the worktree restarting it
        elif marker.read_text().strip() != branch:
            held.append(f"data in .data/offset-{off} belongs to {marker.read_text().strip()}, not {branch}")
    ports = ports_for(off, dict(os.environ))
    own_ports = docker_ports(f"ops-runtime-{off}") if any(v > 0 for v in ports) else set()
    held += blockers(ports, listening(), p.own_pids(off), own_ports)
    if held:
        print(f"refused: offset {off} is in use: " + brief(held, 4), file=sys.stderr)
        return 1
    return 0


def stop(p: Previews, a: argparse.Namespace) -> int:
    mine = [e for e in p.entries() if e["branch"] == a.branch]
    if not mine:
        print(f"no preview for {a.branch}; make wt-list shows them", file=sys.stderr)
        return 1
    e = mine[0]
    if a.dry_run:
        print(f"would stop {a.branch} (offset {e['offset']}) and keep its data")
        return 0
    # make down stops the services by their pid files and runs compose down, which leaves the data volume and the
    # .data/offset-N folder in place; the worktree stays too, so the next make wt for the branch starts warm.
    r = subprocess.run(["make", "-C", e["dir"], "down", f"OPS_PORT_OFFSET={e['offset']}"], env=clean_env(), check=False)
    if r.returncode:
        print("stop failed; the preview stays listed", file=sys.stderr)
        return r.returncode
    Path(e["file"]).unlink(missing_ok=True)
    p.write_page()
    print(f"stopped {a.branch}; its data is kept")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["start", "list", "stop", "check-offset"])
    ap.add_argument("--branch", default="")
    ap.add_argument("--home", default=".")
    ap.add_argument("--worktrees", default="")
    ap.add_argument("--run-root", required=True)
    ap.add_argument("--page", default="")
    ap.add_argument("--data-root", default="")
    ap.add_argument("--offset", type=int, default=0)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    p = Previews(Path(a.run_root), Path(a.page) if a.page else None, Path(a.data_root) if a.data_root else None)
    if a.cmd == "check-offset":
        return check_offset(p, a)
    if a.cmd == "list":
        return p.listing()
    if not a.branch:
        print(
            f"make wt{'-stop' if a.cmd == 'stop' else ''}: name the branch, e.g. BRANCH=feat/apps-salesforce",
            file=sys.stderr,
        )
        return 2
    return start(p, a) if a.cmd == "start" else stop(p, a)


if __name__ == "__main__":
    sys.exit(main())
