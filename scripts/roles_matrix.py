"""Writes the built-in roles' grid into docs/architecture/roles-and-permissions.md between its markers, from
`ops_access`, the one place the grid is defined. The page's prose explains the grid; the table is never typed by hand.

  uv run python scripts/roles_matrix.py          # rewrite the section
  uv run python scripts/roles_matrix.py --check  # exit 1 when the committed section differs (make python-verify)
"""

from __future__ import annotations

import sys
from pathlib import Path

from ops_access import ACTIONS, AREAS, BUILTIN_ROLES, SECURITY_TEAM_ACTIONS

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "architecture" / "roles-and-permissions.md"
BEGIN = "<!-- roles-matrix:begin (generated by scripts/roles_matrix.py from ops_access; do not edit) -->"
END = "<!-- roles-matrix:end -->"


def table() -> str:
    held = {r.id: {(a, x): s for a, x, s in r.grants} for r in BUILTIN_ROLES}
    head = "| Area | Action | " + " | ".join(r.name for r in BUILTIN_ROLES) + " |"
    rows = [head, "|" + "---|" * (len(BUILTIN_ROLES) + 2)]
    for area in AREAS:
        for action in ACTIONS:
            cells = [held[r.id].get((area, action), "") for r in BUILTIN_ROLES]
            if not any(cells):
                continue
            where = " (Security team)" if (area, action) in SECURITY_TEAM_ACTIONS else ""
            rows.append(f"| {area} | {action}{where} | " + " | ".join(c or "no" for c in cells) + " |")
    note = "`all`: every record in the team; `own`: records the person created or owns; `no`: refused."
    return "\n".join([BEGIN, "", note, "", *rows, "", END])


def main() -> int:
    text = PAGE.read_text()
    if BEGIN not in text or END not in text:
        print(f"roles_matrix: {PAGE.relative_to(ROOT)} has no {BEGIN} ... {END} markers")
        return 1
    before, rest = text.split(BEGIN, 1)
    after = rest.split(END, 1)[1]
    new = before + table() + after
    if "--check" in sys.argv:
        if new != text:
            print("roles_matrix: the roles matrix is stale; run uv run python scripts/roles_matrix.py")
            return 1
        return 0
    PAGE.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
