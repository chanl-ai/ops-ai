"""Writes the store inventory into docs/architecture/data.md between its markers: every repository module of every
service, the tables it defines, its repository classes and the guarantees each declares.

  uv run python scripts/store_inventory.py          # rewrite the section
  uv run python scripts/store_inventory.py --check  # exit 1 when the committed section differs (make python-verify)
"""

from __future__ import annotations

import ast
import importlib
import sys
from pathlib import Path

import sqlalchemy as sa

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "architecture" / "data.md"
BEGIN = "<!-- store-inventory:begin (generated by scripts/store_inventory.py; do not edit) -->"
END = "<!-- store-inventory:end -->"


def modules() -> list[tuple[str, str]]:
    """(service, module name) for each `store` package module and `store.py` module under services/*/src."""
    out: list[tuple[str, str]] = []
    for src in sorted(ROOT.glob("services/*-service/src")):
        service = src.parent.name
        for path in sorted([*src.glob("*/store/*.py"), *src.glob("*/store.py")]):
            if path.name == "__init__.py":
                continue
            out.append((service, ".".join(path.relative_to(src).with_suffix("").parts)))
    return out


def defined_names(path: Path) -> set[str]:
    return {
        t.id
        for node in ast.parse(path.read_text()).body
        if isinstance(node, ast.Assign)
        for t in node.targets
        if isinstance(t, ast.Name)
    }


def import_from_root() -> None:
    """Puts this checkout's source first on the import path. The shared virtualenv's editable installs point at the
    working tree, so a check run from an export (the pre-commit gate, verify-head) would otherwise import other
    builders' uncommitted store modules and report their tables as this commit's."""
    sys.path[:0] = [str(p) for p in sorted([*ROOT.glob("packages/*/src"), *ROOT.glob("services/*/src")])]


def rows() -> list[str]:
    lines = ["| Service | Module | Repository | Requires | Tables it defines |", "|---|---|---|---|---|"]
    for service, name in modules():
        mod = importlib.import_module(name)
        if not Path(str(mod.__file__)).resolve().is_relative_to(ROOT):
            raise SystemExit(f"store_inventory: {name} loaded from {mod.__file__}, outside {ROOT}")
        # Tables assigned in this module's own source; a module that imports another's table does not define it.
        own = defined_names(Path(str(mod.__file__)))
        tables = sorted(t.name for k, t in vars(mod).items() if k in own and isinstance(t, sa.Table))
        repos = sorted(
            (k, v)
            for k, v in vars(mod).items()
            if isinstance(v, type) and v.__module__ == name and isinstance(getattr(v, "requires", None), frozenset)
        )
        cell = ", ".join(f"`{t}`" for t in tables) or "none"
        if not repos and not tables:
            continue
        if not repos:
            lines.append(f"| {service} | `{name}` | none: no repository class | | {cell} |")
        for cls_name, cls in repos:
            requires = ", ".join(sorted(str(g.value).upper() for g in cls.requires)) or "none"  # pyright: ignore[reportUnknownMemberType, reportUnknownArgumentType, reportUnknownVariableType]
            lines.append(f"| {service} | `{name}` | `{cls_name}` | {requires} | {cell} |")
    return lines


def render(doc: str) -> str:
    before, rest = doc.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return before + BEGIN + "\n\n" + "\n".join(rows()) + "\n\n" + END + after


def main() -> int:
    import_from_root()
    doc = DOC.read_text()
    if BEGIN not in doc or END not in doc:
        sys.stderr.write(f"store_inventory: {DOC.relative_to(ROOT)} has no inventory markers\n")
        return 1
    fresh = render(doc)
    if "--check" in sys.argv:
        if fresh != doc:
            sys.stderr.write(
                "store_inventory: data.md's inventory is stale; run uv run python scripts/store_inventory.py\n"
            )
            return 1
        return 0
    DOC.write_text(fresh)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
