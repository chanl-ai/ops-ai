"""Generates the SDKs' lower layer from the services' committed OpenAPI documents (`make sdk`; `--check` is the drift
check `make sdk-check` runs). Nothing it writes is edited by hand.

Each public service's document is filtered first: only operations marked `x-ops-public` `sdk` or `both` stay, and
the auth headers every route declares (Authorization, X-Api-Key, X-Team-Id, X-Dev-User) are dropped, because the
client sends them on every call. From the filtered document it writes, per service:

    python/src/ops_ai/_generated/<service>/models.py      TypedDicts, by datamodel-code-generator
    python/src/ops_ai/_generated/<service>/operations.py  one method per operation, sync and async
    typescript/src/generated/<service>.ts                  types, by openapi-typescript
    typescript/src/generated/<service>-operations.ts       each operation's method, path and parameters

    uv run python sdk/generate.py [--check]
"""

from __future__ import annotations

import argparse
import copy
import json
import keyword
import pprint
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

SDK = Path(__file__).resolve().parent
ROOT = SDK.parent
# The services a developer calls; models-service is internal and has no SDK surface.
SERVICES = ("platform", "agents", "tools", "kb", "files", "documents")
PUBLIC = ("sdk", "both")
AUTH_HEADERS = {"authorization", "x-api-key", "x-team-id", "x-dev-user"}
METHODS = ("get", "post", "put", "patch", "delete")
# Generated files are not linted: they follow the documents, not the style rules.
HEADER = "# Generated by sdk/generate.py from services/{service}-service/openapi.json. Do not edit.\n# ruff: noqa\n"


def read_document(service: str, ref: str | None) -> dict[str, Any]:
    """A service's document from the working tree, or as committed at `ref`: in a tree other sessions share, their
    uncommitted route edits would otherwise count as drift in this commit."""
    rel = f"services/{service}-service/openapi.json"
    if ref:
        return json.loads(
            subprocess.run(["git", "show", f"{ref}:{rel}"], cwd=ROOT, capture_output=True, check=True).stdout
        )
    return json.loads((ROOT / rel).read_text())


def public_document(service: str, ref: str | None = None) -> dict[str, Any]:
    doc = read_document(service, ref)
    out = copy.deepcopy(doc)
    for path in list(out["paths"]):
        ops = out["paths"][path]
        for method in list(ops):
            op = ops[method]
            if method not in METHODS:
                continue
            if op.get("x-ops-public") not in PUBLIC:
                del ops[method]
                continue
            op["parameters"] = [
                p for p in op.get("parameters", []) if not (p["in"] == "header" and p["name"].lower() in AUTH_HEADERS)
            ]
        if not any(m in ops for m in METHODS):
            del out["paths"][path]
    return out


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).replace("-", "_").lower()
    return f"{s}_" if keyword.iskeyword(s) else s


def class_name(schema: str) -> str:
    """The class name datamodel-code-generator gives a schema: `Envelope_ListResult_FileSummary__` ->
    `EnvelopeListResultFileSummary`."""
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", schema) if part)


def ref_name(schema: dict[str, Any]) -> str | None:
    r = schema.get("$ref")
    return r.rsplit("/", 1)[-1] if isinstance(r, str) else None


def py_type(schema: dict[str, Any], classes: set[str]) -> str:
    """A Python annotation for a schema, naming a generated TypedDict where there is one."""
    name = ref_name(schema)
    if name:
        c = class_name(name)
        return c if c in classes else "Any"
    if "anyOf" in schema:
        parts = [py_type(s, classes) for s in schema["anyOf"] if s.get("type") != "null"]
        return parts[0] if len(parts) == 1 else "Any"
    t = schema.get("type")
    if t == "array":
        return f"list[{py_type(schema.get('items', {}), classes)}]"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}.get(t or "", "Any")


def operations(doc: dict[str, Any]) -> list[dict[str, Any]]:
    """Each operation as the clients need it: method, path, parameters by where they go, body and success shape."""
    schemas = doc.get("components", {}).get("schemas", {})
    out: list[dict[str, Any]] = []
    for path, ops in doc["paths"].items():
        for method in METHODS:
            op = ops.get(method)
            if op is None:
                continue
            params = op.get("parameters", [])
            body = op.get("requestBody", {}).get("content", {})
            ok = next((r for s, r in op["responses"].items() if s.startswith("2")), {})
            content = ok.get("content") or {}
            json_schema = (content.get("application/json") or {}).get("schema") or {}
            data = json_schema
            env = ref_name(json_schema)
            if env and "data" in schemas.get(env, {}).get("properties", {}):
                data = schemas[env]["properties"]["data"]
            out.append(
                {
                    "id": op["operationId"],
                    "method": method.upper(),
                    "path": path,
                    "summary": (op.get("summary") or "").strip(),
                    "pathParams": [p["name"] for p in params if p["in"] == "path"],
                    "query": [p["name"] for p in params if p["in"] == "query"],
                    "headers": [p["name"] for p in params if p["in"] == "header"],
                    "body": "json" if "application/json" in body else ("multipart" if body else None),
                    "bodySchema": (body.get("application/json") or {}).get("schema"),
                    "stream": "text/event-stream" in content,
                    "data": data,
                    "params": {p["name"]: p.get("schema", {}) for p in params},
                }
            )
    return out


def python_operations(service: str, ops: list[dict[str, Any]], classes: set[str]) -> str:
    table = {
        o["id"]: {k: o[k] for k in ("method", "path", "pathParams", "query", "headers", "body", "stream")} for o in ops
    }
    lines = [
        HEADER.format(service=service),
        "from __future__ import annotations\n",
        "from typing import Any\n",
        "from ..._transport import AsyncTransport, Operation, Transport",
        "from .models import *  # noqa: F403\n",
        f"SERVICE = {service!r}",
        f"OPERATIONS: dict[str, Operation] = {pprint.pformat(table, sort_dicts=True, width=120)}",
        "",
    ]
    for cls, transport, aw in (("Operations", "Transport", ""), ("AsyncOperations", "AsyncTransport", "await ")):
        lines += [
            "",
            f"class {cls}:",
            f'    """Every public operation of {service}-service, by its operationId."""',
            "",
            f"    def __init__(self, transport: {transport}) -> None:",
            "        self._t = transport",
        ]
        for o in ops:
            args = ["self"]
            for p in o["pathParams"]:
                args.append(f"{snake(p)}: {py_type(o['params'][p], classes)}")
            if o["body"]:
                args.append(f"body: {py_type(o['bodySchema'] or {}, classes) if o['body'] == 'json' else 'Any'}")
            # Two wire names can share a Python name (`workflowId` and `workflow_id` on one route): the first is kept.
            taken = {snake(p) for p in o["pathParams"]}
            query_names = [q for q in o["query"] if not (snake(q) in taken or taken.add(snake(q)))]
            header_names = [h for h in o["headers"] if not (snake(h) in taken or taken.add(snake(h)))]
            kw = [f"{snake(q)}: {py_type(o['params'][q], classes)} | None = None" for q in query_names]
            kw += [f"{snake(h)}: str | None = None" for h in header_names]
            sig = ", ".join(args + (["*", *kw] if kw else []))
            ret = "Any" if o["stream"] else py_type(o["data"], classes)
            path = "{" + ", ".join(f"{p!r}: {snake(p)}" for p in o["pathParams"]) + "}"
            query = "{" + ", ".join(f"{q!r}: {snake(q)}" for q in query_names) + "}"
            headers = "{" + ", ".join(f"{h!r}: {snake(h)}" for h in header_names) + "}"
            call = f"self._t.call(SERVICE, OPERATIONS[{o['id']!r}], {path}, {query}, {headers}"
            call += ", body)" if o["body"] else ", None)"
            doc = o["summary"] or f"{o['method']} {o['path']}"
            prefix = "async " if aw else ""
            lines += [
                "",
                f"    {prefix}def {o['id']}({sig}) -> {ret}:",
                f"        {json.dumps(doc)}",
                f"        return {aw}{call}  # type: ignore[no-any-return]",
            ]
    return "\n".join(lines) + "\n"


def typescript_operations(service: str, ops: list[dict[str, Any]]) -> str:
    table = {
        o["id"]: {k: o[k] for k in ("method", "path", "pathParams", "query", "headers", "body", "stream")} for o in ops
    }
    header = f"// Generated by sdk/generate.py from services/{service}-service/openapi.json. Do not edit.\n"
    body = json.dumps(table, indent=2, sort_keys=True)
    return f"{header}export const {service.replace('-', '_')}Operations = {body} as const;\n"


def generate(out: Path, ref: str | None = None) -> None:
    py_root = out / "python" / "src" / "ops_ai" / "_generated"
    ts_root = out / "typescript" / "src" / "generated"
    py_root.mkdir(parents=True, exist_ok=True)
    ts_root.mkdir(parents=True, exist_ok=True)
    (py_root / "__init__.py").write_text('"""Generated by sdk/generate.py. Do not edit."""\n')
    with tempfile.TemporaryDirectory() as tmp:
        for service in SERVICES:
            doc = public_document(service, ref)
            spec = Path(tmp) / f"{service}.json"
            spec.write_text(json.dumps(doc))
            pkg = py_root / service
            pkg.mkdir(exist_ok=True)
            (pkg / "__init__.py").write_text(HEADER.format(service=service))
            models = pkg / "models.py"
            subprocess.run(
                [
                    "datamodel-codegen",
                    "--input", str(spec),
                    "--input-file-type", "openapi",
                    "--output", str(models),
                    "--output-model-type", "typing.TypedDict",
                    "--target-python-version", "3.11",
                    "--use-union-operator",
                    "--use-standard-collections",
                    "--disable-timestamp",
                    "--custom-file-header", HEADER.format(service=service).strip(),
                ],
                check=True,
                capture_output=True,
            )  # fmt: skip
            classes = set(re.findall(r"^class (\w+)\(", models.read_text(), re.M))
            ops = operations(doc)
            (pkg / "operations.py").write_text(python_operations(service, ops, classes))
            subprocess.run(
                ["pnpm", "--dir", str(SDK / "typescript"), "exec", "openapi-typescript", str(spec), "-o",
                 str(ts_root / f"{service}.ts")],
                check=True,
                capture_output=True,
            )  # fmt: skip
            (ts_root / f"{service}-operations.ts").write_text(typescript_operations(service, ops))
    subprocess.run(["uv", "run", "ruff", "format", "--quiet", str(py_root)], check=True, cwd=ROOT)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the committed layer differs")
    ap.add_argument(
        "--ref", help="with --check: compare the documents and the generated layer as committed at this ref"
    )
    a = ap.parse_args()
    if not a.check:
        for stale in (SDK / "python/src/ops_ai/_generated", SDK / "typescript/src/generated"):
            shutil.rmtree(stale, ignore_errors=True)
        generate(SDK)
        print(f"sdk: generated {len(SERVICES)} services")
        return 0
    with tempfile.TemporaryDirectory() as tmp, tempfile.TemporaryDirectory() as committed:
        generate(Path(tmp), a.ref)
        against = SDK
        if a.ref:
            layer = ["sdk/python/src/ops_ai/_generated", "sdk/typescript/src/generated"]
            archive = subprocess.run(["git", "archive", a.ref, *layer], cwd=ROOT, capture_output=True, check=True)
            subprocess.run(["tar", "-x", "-C", committed], input=archive.stdout, check=True)
            against = Path(committed) / "sdk"
        drift = []
        for rel in ("python/src/ops_ai/_generated", "typescript/src/generated"):
            got = subprocess.run(
                ["diff", "-r", "-x", "__pycache__", str(Path(tmp) / rel), str(against / rel)],
                capture_output=True,
                text=True,
                check=False,
            )
            if got.returncode:
                drift.append(got.stdout[:2000])
        if drift:
            print(
                "sdk-check: the generated layer differs from the services' documents; run `make sdk`\n"
                + "\n".join(drift)
            )
            return 1
    print(f"sdk-check: the generated layer matches {len(SERVICES)} services' documents")
    return 0


if __name__ == "__main__":
    sys.exit(main())
